"""Dependency rules for somax, from geostack's dependency graph.

somax sits in GeoModels, tier 0 (models; never import each other). Its packages
must not import or depend on plumax, radtrax: they sit above it, or beside it
in the same tier. Every import of a stack library is declared, as a dependency
or an extra. Dev, docs and tutorial dependency groups are not checked.

The rules: https://github.com/jejjohnson/geostack/blob/main/docs/api/dependency_graph.md

Generated by ``python scripts/dependency_graph.py --guard somax`` in
jejjohnson/geostack, from the layers and tiers there; change them there and
regenerate this file rather than editing it.
"""

